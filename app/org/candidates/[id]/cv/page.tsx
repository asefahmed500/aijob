"use client";

import { useCallback, useEffect, useState } from "react";
import Link from "next/link";
import { api, type CvRecord } from "@/lib/api";
import { Button, buttonVariants } from "@/components/ui/button";
import { Badge } from "@/components/ui/badge";
import { Alert, AlertDescription, AlertTitle } from "@/components/ui/alert";

type Props = { params: Promise<{ id: string }> };

function cvLines(value: string): string[] {
  return value.split("\n").map((line) => line.trim()).filter(Boolean);
}

export default function CandidateCvPage({ params }: Props) {
  const [id, setId] = useState<string | null>(null);
  const [name, setName] = useState("");
  const [email, setEmail] = useState("");
  const [cv, setCv] = useState<CvRecord | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);

  const load = useCallback(async (candidateId: string) => {
    try {
      const record = await api.getCandidate(candidateId);
      setName(record.name);
      setEmail(record.email);
      setCv(record.cvs[0] ?? null);
    } catch (cause) {
      setError(cause instanceof Error ? cause.message : "Could not load CV");
    }
  }, []);

  useEffect(() => {
    void params.then(async (resolved) => {
      setId(resolved.id);
      await load(resolved.id);
    });
  }, [params, load]);

  async function generate() {
    if (!id) return;
    setBusy(true);
    setError(null);
    try {
      await api.generateCv(id);
      await load(id);
    } catch (cause) {
      setError(cause instanceof Error ? cause.message : "Could not generate CV");
    } finally {
      setBusy(false);
    }
  }

  if (!id) return <main className="flex flex-1 items-center justify-center">Loading…</main>;

  return (
    <main className="flex flex-1 flex-col px-6 py-10">
      <div className="mx-auto w-full max-w-4xl">
        <div className="cv-no-print mb-6 flex flex-wrap items-center justify-between gap-3">
          <div>
            <h1 className="text-2xl font-semibold tracking-tight">Candidate CV</h1>
            <p className="text-sm text-muted-foreground">Generated only from the candidate&apos;s resume text.</p>
          </div>
          <div className="flex flex-wrap gap-2">
            <Link className={buttonVariants({ variant: "outline" })} href={`/org/candidates/${id}`}>Back to candidate</Link>
            {cv ? (
              <Button onClick={() => window.print()}>Print / Save PDF</Button>
            ) : (
              <Button variant="soft" onClick={() => void generate()} loading={busy}>
                Generate CV
              </Button>
            )}
          </div>
        </div>

        {error ? <Alert variant="destructive" className="cv-no-print mb-4"><AlertTitle>Error</AlertTitle><AlertDescription>{error}</AlertDescription></Alert> : null}

        {cv ? (
          <article className="cv-print rounded-xl border bg-card p-10 text-card-foreground shadow-sm">
            <header className="border-b pb-6">
              <h2 className="text-3xl font-semibold tracking-tight">{cv.headline}</h2>
              <p className="mt-1 text-sm text-muted-foreground">{email}</p>
              <div className="mt-3 flex flex-wrap gap-2">
                <Badge variant="secondary">Version {cv.version}</Badge>
                <Badge variant="outline">Generated by {cv.source}</Badge>
              </div>
            </header>

            <section className="mt-8">
              <h3 className="text-xs font-semibold uppercase tracking-widest text-muted-foreground">Profile</h3>
              <p className="mt-2 text-sm leading-relaxed">{cv.summary}</p>
            </section>

            {cv.skills ? (
              <section className="mt-8">
                <h3 className="text-xs font-semibold uppercase tracking-widest text-muted-foreground">Skills</h3>
                <div className="mt-2 flex flex-wrap gap-2">
                  {cvLines(cv.skills).map((skill, index) => <Badge key={index} variant="secondary">{skill}</Badge>)}
                </div>
              </section>
            ) : null}

            {cv.experience ? (
              <section className="mt-8">
                <h3 className="text-xs font-semibold uppercase tracking-widest text-muted-foreground">Experience</h3>
                <ul className="mt-2 list-inside list-disc space-y-2 text-sm leading-relaxed">
                  {cvLines(cv.experience).map((line, index) => <li key={index}>{line}</li>)}
                </ul>
              </section>
            ) : null}

            {cv.education ? (
              <section className="mt-8">
                <h3 className="text-xs font-semibold uppercase tracking-widest text-muted-foreground">Education</h3>
                <ul className="mt-2 list-inside list-disc space-y-2 text-sm leading-relaxed">
                  {cvLines(cv.education).map((line, index) => <li key={index}>{line}</li>)}
                </ul>
              </section>
            ) : null}

            <footer className="mt-10 border-t pt-4 text-xs text-muted-foreground">
              {name} · CV generated from resume text · Joby
            </footer>
          </article>
        ) : (
          <Alert>
            <AlertTitle>No CV yet</AlertTitle>
            <AlertDescription>Generate a structured CV to preview and print it here.</AlertDescription>
          </Alert>
        )}
      </div>
    </main>
  );
}
